import Foundation
import CoreLocation

nonisolated struct Coordinate: Codable, Hashable, Sendable {
    var latitude: Double
    var longitude: Double

    var clLocation: CLLocation { CLLocation(latitude: latitude, longitude: longitude) }
    var clCoordinate: CLLocationCoordinate2D { .init(latitude: latitude, longitude: longitude) }

    func distanceMiles(to other: Coordinate) -> Double {
        clLocation.distance(from: other.clLocation) / 1609.344
    }

    /// Richardson, TX — used when location is unavailable (simulator / mock mode).
    static let demoFallback = Coordinate(latitude: 32.9483, longitude: -96.7299)
}

nonisolated struct Store: Codable, Identifiable, Hashable, Sendable {
    var id: String
    var chain: String
    var name: String
    var address: String
    var coordinate: Coordinate
    var distanceMiles: Double
    var isKroger: Bool
}

nonisolated struct PriceQuote: Identifiable, Hashable, Sendable {
    var store: Store
    var price: Double
    var promoPrice: Double?
    /// True when the price is generated by `MockPriceService` (not a real price).
    var isSample: Bool
    var productDescription: String?

    var id: String { store.id }
    var effectivePrice: Double { promoPrice.map { min($0, price) } ?? price }
}

/// Chains searched through MapKit (no public price APIs → sample prices).
nonisolated enum OtherChain: String, CaseIterable, Sendable {
    case walmart = "Walmart"
    case heb = "H-E-B"
    case target = "Target"
    case aldi = "Aldi"
    case tomThumb = "Tom Thumb"

}
