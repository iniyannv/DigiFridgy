import Foundation
import CoreLocation

nonisolated struct Coordinate: Codable, Hashable, Sendable {
    var latitude: Double
    var longitude: Double

    var clLocation: CLLocation { CLLocation(latitude: latitude, longitude: longitude) }
    var clCoordinate: CLLocationCoordinate2D { .init(latitude: latitude, longitude: longitude) }

    func distanceMiles(to other: Coordinate) -> Double {
        clLocation.distance(from: other.clLocation) / 1609.344
    }

    /// Richardson, TX — used when location is unavailable (simulator / mock mode).
    static let demoFallback = Coordinate(latitude: 32.9483, longitude: -96.7299)
}

nonisolated struct Store: Codable, Identifiable, Hashable, Sendable {
    var id: String
    var chain: String
    var name: String
    var address: String
    var coordinate: Coordinate
    var distanceMiles: Double
    var isKroger: Bool
}

nonisolated struct PriceQuote: Identifiable, Hashable, Sendable {
    enum Availability: Hashable, Sendable {
        /// Real price at this store from the Kroger API.
        case live
        /// Real price from the chain's website (walmart.com), the same for every store of the chain.
        case online
        /// Generated by `MockPriceService` (chains without a public price API).
        case sample
        /// The store doesn't carry this product.
        case notCarried
        /// The price lookup failed (network / API error).
        case failed
    }

    var store: Store
    /// Nil when there's no price (`notCarried` / `failed`).
    var price: Double?
    var promoPrice: Double?
    var availability: Availability
    var productDescription: String?

    var id: String { store.id }
    var isSample: Bool { availability == .sample }
    var hasPrice: Bool { price != nil }
    var effectivePrice: Double? { price.map { p in promoPrice.map { min($0, p) } ?? p } }
}

/// Chains searched through MapKit. Walmart gets walmart.com prices when its key is set; the rest get sample prices.
nonisolated enum OtherChain: String, CaseIterable, Sendable {
    case walmart = "Walmart"
    case heb = "H-E-B"
    case target = "Target"
    case aldi = "Aldi"
    case tomThumb = "Tom Thumb"

}
